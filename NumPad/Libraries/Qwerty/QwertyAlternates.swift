import Foundation

enum QwertyAlternates {
    private static let map: [String: [String]] = [
        "a": ["à", "á", "â", "ä", "æ", "ã", "å", "ā"],
        "c": ["ç", "ć", "č"],
        "e": ["è", "é", "ê", "ë", "ē", "ė", "ę"],
        "i": ["ì", "í", "î", "ï", "ī"],
        "n": ["ñ", "ń"],
        "o": ["ò", "ó", "ô", "ö", "õ", "ø", "ō", "œ"],
        "s": ["ß", "ś", "š"],
        "u": ["ù", "ú", "û", "ü", "ū"],
        "y": ["ÿ", "ý"],
        "'": ["‘", "’", "‛"],
        "\"": ["“", "”", "„", "«", "»"],
        "-": ["—", "–", "•"],
        "$": ["¢", "£", "€", "¥", "₩", "₽"],
        "£": ["$", "€", "¥"],
        "€": ["$", "£", "¥"]
    ]

    static func values(for key: String) -> [String] {
        let base = key.lowercased()
        return map[base] ?? []
    }
}

